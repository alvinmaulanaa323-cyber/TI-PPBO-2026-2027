public class DataPribadi {
    public static void main(String[] args) {
        // Variabel untuk menyimpan umur
        int umur = 20;

        // Variabel untuk menyimpan tinggi badan
        double tinggiBadan = 168;

        // Variabel untuk menyimpan inisial
        char inisial = 'A';

        // Variabel untuk menyimpan status mahasiswa aktif
        boolean mahasiswaAktif = true;

        System.out.println("Umur: " + umur);
        System.out.println("Tinggi Badan: " + tinggiBadan);
        System.out.println("Inisial: " + inisial);
        System.out.println("Mahasiswa Aktif: " + mahasiswaAktif);
    }
}